// Writes openapi/openapi.yaml from the zod schemas each API module registers (Contracts §2).
// Generator owner: Dev 2 (v1.1) / contract CI job: Dev 6 (v1.2). The output is committed; CI fails on a diff.
import { buildOpenApiDocument } from '@dsa/api/openapi';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { stringify } from 'yaml';

const outFile = path.resolve(import.meta.dirname, '..', 'openapi', 'openapi.yaml');
const header = '# GENERATED by tools/gen-openapi.ts from the zod schemas. Do not edit by hand.\n';

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, header + stringify(buildOpenApiDocument(), { lineWidth: 0 }));
console.log(`wrote ${path.relative(process.cwd(), outFile)}`);
